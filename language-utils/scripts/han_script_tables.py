#!/usr/bin/env python3
"""Derive conservative script-exclusive Han tables from CC-CEDICT.

Usage: python3 language-utils/scripts/han_script_tables.py .cache/readings/cedict.gz
Source: https://www.mdbg.net/chinese/dictionary?page=cedict (CC BY-SA 4.0).
Variant-only definitions are not evidence of script exclusivity. Any occurrence
on the opposite side, including a variant entry, vetoes exclusivity. Thus forms
with legitimate uses in both scripts (乾/著/沈/妳, etc.) stay accepted.
"""
import gzip
import hashlib
from pathlib import Path
import re
import sys

source = Path(sys.argv[1])
rows = []
for line in gzip.open(source, 'rt', encoding='utf-8'):
    match = re.match(r'(\S+) (\S+) \[[^\]]+\] /(.*)/', line)
    if match:
        rows.append(match.groups())


def han(c):
    return '㐀' <= c <= '鿿' or '豈' <= c <= '﫿' or '\U00020000' <= c <= '\U000323af'


def variant_only(gloss):
    return all(re.search(r'\bvariant of\b', sense) for sense in gloss.split('/') if sense)


all_traditional = {c for t, _, _ in rows for c in t if han(c)}
all_simplified = {c for _, s, _ in rows for c in s if han(c)}
traditional = {c for t, _, g in rows if not variant_only(g) for c in t if han(c)}
simplified = {c for _, s, g in rows if not variant_only(g) for c in s if han(c)}
# 妳 is a gendered second-person spelling, not a script conversion of 你.
traditional.discard('妳')
output = Path(__file__).resolve().parents[1] / 'src' / 'han_script_tables.rs'
output.write_text(
    '// Generated by language-utils/scripts/han_script_tables.py from CC-CEDICT.\n'
    '// Source: https://www.mdbg.net/chinese/dictionary?page=cedict (CC BY-SA 4.0).\n'
    f'// Source gzip SHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()}\n'
    '// Variant-only entries supply no exclusivity evidence; either opposite-side use vetoes it.\n'
    f'pub const SIMPLIFIED_ONLY: &str = "{"".join(sorted(simplified - all_traditional))}";\n'
    f'pub const TRADITIONAL_ONLY: &str = "{"".join(sorted(traditional - all_simplified))}";\n',
    encoding='utf-8',
)
print(f'{output}: simplified={len(simplified - all_traditional)}, traditional={len(traditional - all_simplified)}')
